"""문제 생성 프롬프트 빌더.

원칙(v1): **원문(source_text)에서만 출제. 외부 지식 소싱 금지.**
→ 검증(원문대조)·저작권 논리("파생 문항만 자산화")가 이 원칙 위에서 성립한다.
"""
from app.features.problems.schemas import ConceptInput

# 레벨 정의 — 프롬프트에 그대로 주입해 난이도 축을 고정.
# 레벨 정의는 levels.assess()의 판정 기준과 **같은 말**이어야 한다. 서술만
# 다르면 모델이 지킬 수 없는 규칙이 되어 강등만 반복된다.
_LEVEL_GUIDE = """레벨 정의 — 아래 기준으로 채점되며, 어기면 낮은 레벨로 강등된다:

- level 1 (암기): 원문의 용어·정의를 그대로 재인출. 정답 보기가 근거 문구와
  사실상 같아도 된다.
- level 2 (적용): **정답 보기가 근거 문구를 그대로 옮긴 것이면 안 된다.**
  용어↔설명을 매핑하거나 상황에 적용해야 풀리게 하라.
  (O) 근거 "단편화를 '최소화'하는 분할 영역에 데이터 배치" → 정답 "Best Fit"
  (X) 같은 근거 → 정답 "단편화를 최소화"   ← 근거를 읽으면 바로 보이므로 L1이다
- level 3 (심화): **원문의 서로 다른 두 곳 이상을 종합해야** 풀리게 하라.
  두 항목의 비교·구분·인과가 여기 해당한다. source_evidence에는 두 인용을
  각각 원문 그대로 옮겨 줄바꿈으로 구분해 담아라. level 2 규칙도 함께 지킨다.
  (O) "최초 적합은 첫 번째 영역, 최적 적합은 단편화 최소 영역에 배치"
  (X) "최악 적합이 목표로 하는 것은? → 단편화를 최대화"  ← 한 줄 되묻기, L1이다"""

# 유형별 규칙. 정답 자료형이 다르므로 형식을 어기면 스키마 단계에서 폐기된다.
_TYPE_GUIDE = """문항 유형 — 아래 넷 중에서 고르고, 형식을 정확히 지켜라:

- "mcq" (4지선다, 정답 1개): options 4개, answer는 그중 하나와 **글자까지 같은 문자열**.
- "multi" (모두 고르기): options 4~6개, answer는 **정답 보기들의 배열**.
  정답은 2개 이상이되 보기 전체일 수는 없다(고를 것이 없어진다).
  질문은 "…에 해당하는 것을 **모두 고르시오**" 하나의 기준으로만 묻는다.
  (X) "A인 것과 B인 것은 **각각** 무엇인가?"
      → 둘을 짝지어 물으면 어느 보기가 어느 쪽인지 표시할 수 없다. 이런 문항은 폐기된다.
  (O) "배치 전략에 해당하는 것을 모두 고르시오"
- "ox" (참/거짓): options는 빈 배열, answer는 "O" 또는 "X".
  거짓 문장은 원문 서술에서 **핵심 한 곳만** 비틀어 만든다(예: '최소화'→'최대화').
  원문에 없는 내용을 지어내 거짓 문장을 만들지 마라.
- "order" (순서 배열): 원문에 **절차·단계·인과의 흐름이 명시된 경우에만** 쓴다.
  options는 섞인 항목 3~5개, answer는 **보기 전체를 올바른 순서로 배열한 배열**.
  (X) "원문에 나온 순서대로 배열하시오"
      → 문서에 적힌 차례를 묻는 것은 내용 이해가 아니라 문서 암기다. 금지.
  (X) 나란히 나열된 항목(예: 최초 적합·최적 적합·최악 적합)을 배열시키기
      → 이들 사이에는 순서가 없다.
  (O) "요청이 들어온 뒤 페이지가 교체되기까지의 처리 순서를 배열하시오"
  순서가 원문 내용으로 **유일하게** 정해지지 않으면 이 유형을 쓰지 마라.

레벨별로 적합한 유형:
- level 1 → mcq, ox
- level 2 → mcq, multi
- level 3 → multi, order, mcq(비교형)
한 레벨 안에서도 유형을 섞어라. 같은 유형만 반복하면 문제은행의 가치가 떨어진다."""

_OUTPUT_SCHEMA = """반드시 아래 JSON 객체 하나만 출력한다(설명·코드펜스 금지):
{
  "problems": [
    {
      "level": <1|2|3>,
      "type": "mcq" | "multi" | "ox" | "order",
      "question": "질문(한국어)",
      "options": ["보기1", "보기2", "보기3", "보기4"],
      "answer": "mcq는 보기 하나(문자열), ox는 \\"O\\"/\\"X\\", multi·order는 배열",
      "explanation": "정답 근거 해설",
      "source_evidence": "원문에 실제로 존재하는 근거 문구를 그대로 인용"
    }
  ],
  "coverage_note": "원문이 특정 레벨을 뒷받침하기 부족하면 그 사실을 여기에 정직하게 적는다(없으면 빈 문자열)"
}"""


def build_generation_prompt(
    subject: str,
    concept: ConceptInput,
    per_level: int,
    feedback: str | None = None,
) -> str:
    keywords = ", ".join(concept.keywords) if concept.keywords else "(없음)"
    # 재시도 시 직전 부족/폐기 사유를 최상단에 주입 — 모델이 무엇을 고쳐야
    # 하는지 먼저 읽게 한다(자기수정 루프의 신호).
    feedback_block = (
        f"[직전 시도 피드백 — 반드시 반영]\n{feedback}\n\n" if feedback else ""
    )
    return f"""{feedback_block}너는 검증된 문제은행을 위한 출제 에이전트다. 과목은 "{subject}", 개념은 "{concept.title}".

[핵심 규칙]
1. 아래 <원문>에 실제로 적힌 내용만으로 출제한다. 원문에 없는 사실·수치·용어를 지어내지 마라.
2. 각 문항의 source_evidence는 <원문>에 그대로 존재하는 문구여야 한다(요약·창작 금지).
2-1. 비교·종합 문항처럼 원문 **여러 곳**을 근거로 쓸 때는, 각 인용을 원문 그대로
   옮기고 **줄바꿈(\n)으로 구분**해 이어 붙여라. 두 인용을 한 문장으로 합치거나
   연결어를 끼워 넣으면 원문과 글자가 달라져 폐기된다.
3. answer는 반드시 options 중 하나와 글자까지 동일해야 한다.
4. 오답 보기도 그 개념 맥락에서 그럴듯해야 한다(무관하거나 명백히 우스운 보기 금지).
5. 개념명이 곧 정답이 되어 정답이 유출되는 문항을 만들지 마라.
6. 원문이 특정 레벨을 뒷받침하지 못하면 그 레벨 문항 수를 줄이고 coverage_note에 사유를 적는다.
7. 모든 문항은 선택형이다. question은 "다음 중 …은?", "…에 해당하는 것을 모두 고르시오",
   "…순서대로 배열하시오"처럼 보기 선택을 요구하는 어투로 쓴다.
   "설명하시오/서술하시오/기술하시오" 같은 **서술을 요구하는 지시문은 금지**한다.

{_LEVEL_GUIDE}

{_TYPE_GUIDE}

목표: level 1/2/3 각각 최대 {per_level}문항을 만든다.
참고 키워드: {keywords}

<원문>
{concept.source_text}
</원문>

{_OUTPUT_SCHEMA}"""
