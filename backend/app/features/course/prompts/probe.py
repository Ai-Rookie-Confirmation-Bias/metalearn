"""24 확인 문항 — **오답만 만든다.**

문항을 통째로 LLM에게 시키면 못 쓴다. 실측:

    직접 생성 (책 밖)   1/6    정답 번호가 보기와 안 맞음, 정답이 둘
    직접 생성 (책 안)   1/4    "아래 코드에서…"인데 코드가 없음
    **오답만 생성**     14/15  ✅

차이는 하나다. **LLM이 정답을 정하지 않는다.** 정답은 우리가 이미 아는 것을
쓰고(원문 문장, 또는 2회 생성이 일치한 정의), LLM은 그걸 망가뜨리기만 한다.
정답 번호가 어긋날 자리도, 정답이 둘이 될 자리도 없다.

만든 오답은 유사도로 한 번 더 거른다(`diagnostic._usable`):

    0.98  정답을 거의 그대로 베낌 → 정답이 둘이 된다        버림
    0.77  뜻이 다르지만 같은 결의 문장                       채택
    0.83  한 군데만 뒤집은 문장                              채택
    0.25  딴소리                                             버림 (안 고른다)

이 문항의 쓰임은 **점수가 아니다.** 학습자가 "안다"고 한 것이 정말인지
한 번 재보는 것뿐이라, 놓쳐도 그 항목이 `known`으로 남을 뿐이다.
"""
from __future__ import annotations

SYSTEM = (
    "너는 객관식 문항의 **오답 보기**만 만드는 도구다. "
    "정답은 이미 정해져 있고 너는 그것을 고르게 하면 안 된다. "
    "출력은 지정한 JSON만 따른다."
)

# 한 문항의 오답 수. 정답 1 + 오답 3 = 보기 4개.
DISTRACTORS = 3


def build_prompt(*, subject: str, item: str, answer: str) -> str:
    """`item`을 묻는 문항의 오답 `DISTRACTORS`개.

    정답 문장을 그대로 주고 "이걸 틀리게 바꿔라"라고 시킨다. 무엇이 정답인지
    묻지 않으므로 LLM이 답을 정할 여지가 없다.
    """
    return f"""아래는 '{subject}'의 '{item}'에 대한 **맞는 설명**이다.

[맞는 설명]
{answer}

이 설명을 **틀리게** 바꾼 문장을 {DISTRACTORS}개 만들어라. 객관식 오답으로 쓴다.

[규칙]
1. 각 오답은 **딱 한 군데만** 틀려야 한다. 숫자를 바꾸거나, 방향을 뒤집거나,
   비슷한 다른 개념의 설명으로 바꾼다.
2. 그 분야를 아는 사람은 **왜 틀렸는지 짚을 수 있어야** 한다.
   막연히 어색한 문장은 쓸모없다.
3. 맞는 설명을 **말만 바꿔 옮기지 마라.** 그러면 정답이 둘이 된다.
4. 명백히 딴 분야 이야기를 쓰지 마라. 아무나 골라낸다.
5. 길이와 말투를 맞는 설명과 비슷하게 유지하라 — 길이로 정답이 티나면 안 된다.

JSON 하나만 출력한다(설명·코드펜스 금지):
{{"distractors": ["...", "...", "..."]}}"""


DEFINE_SYSTEM = (
    "너는 개념 하나를 한 문장으로 정의한다. "
    "모르면 모른다고 한다. 지어내지 않는다."
)


def build_define_prompt(*, subject: str, item: str) -> str:
    """책 밖 항목의 정답 문장을 만든다. **두 번 불러 일치할 때만 쓴다.**

    선수 항목은 코스 자료에 없는 것이라(그게 선수의 정의다) 원문에서 정답을
    가져올 수 없다. 그래서 생성하되 혼자 믿지 않는다 — 같은 물음을 두 번 던져
    두 답의 유사도가 0.75 이상일 때만 정답으로 쓴다(실측 일치 시 0.84~0.91).

    한 문장으로 묶는 이유: 길면 두 답이 절대 안 겹쳐서 일치 검사가 무의미해진다.
    """
    return f"""'{subject}' 분야의 '{item}'을(를) **한 문장**으로 정의하라.

[규칙]
1. 교재에 실릴 만한 정확한 정의여야 한다.
2. 한 문장. 예시·비유·부연 없이.
3. 확실하지 않으면 정의를 지어내지 말고 빈 문자열을 넣어라.

JSON 하나만 출력한다(설명·코드펜스 금지):
{{"definition": "..."}}"""
