# "이 보기들 중 실수로 맞게 써진 게 있나"를 LLM에게 물었다. **뺐다.**
#
# 세 번 만에 세 번째가 이랬다(실측, 묶음 5개 × 오답 5개):
#
#     0  {"also_correct": []}
#     1  {"also_correct": []}
#     2  {"also_correct": [[0,0],[0,1],...[4,4]]}   ← 25개 전부
#
# 묶음을 하나만 주면 3/3 깨끗한데 5~7개를 주면 가끔 "전부 버려"로 뒤집힌다.
# 그러면 그 라운드 문항이 통째로 사라진다. 문구를 두 번 갈아엎어도
# (`골라내라` → `also_correct`) 이 모드가 남았다. 지시문으로 못 고친다.
#
# 유사도로 자르는 것도 안 된다. **좋은 오답일수록 정답과 닮기 때문이다** —
# 아래 규칙 1이 "딱 한 군데만" 틀리라고 하니 나머지는 그대로 베껴 온다.
# 실측에서 한 라운드 30개 중 28개가 0.94 이상이었고, 0.92로 자르면 가장 좋은
# 오답부터 사라진다. 같은 모델이 실행마다 통째로 다시 쓰기(0.58~0.67)와
# 한 단어 바꾸기(1.000)를 오가서 문턱을 세울 자리가 없다.
#
