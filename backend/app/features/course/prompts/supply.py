"""26 조달 — **명세만 쓴다. 내용은 안 만든다.**

## 왜 명세만인가

설명을 여기서 생성하면 두 번 만드는 꼴이다. 학습층은 이미 성향(비유/정의/표/왜)
과 진도에 맞춰 설명을 쓰는 에이전트를 갖고 있고(`curriculum/`), 그쪽이 원문이
없을 때 `Concept.definition`을 근거로 쓴다(`curriculum/service.py`).

그래서 우리가 남기는 건 **뭘 가르쳐야 하는가**뿐이다.

    { 이름: "스택",
      가르칠 것: "LIFO 구조와 push/pop, 함수 호출 스택에서의 쓰임",
      키워드: ["LIFO", "push", "pop", "top", "호출 스택"] }

조각(`DocSegment`)이 없는 `Concept` 행으로 저장한다. 화면은 이 단원에 원문이
없다는 걸 `segments`가 비어 있는 것으로 알고, 학습층이 거기서 생성한다.

## 왜 과목 통째로 만드나

만들어지는 자료는 **(분야, 과목) 소유**다. 지금 이 사람이 모르는 항목만 담으면
다음 사람이 못 쓴다 — 그 사람은 다른 항목을 모른다. 사용자별 차이는 자료가
아니라 `course_topics.plan`(brief/skip)이 들고 있다.

## 정확성

지어낼 위험이 있다. 다만 여기 결과는 **학습층 프롬프트의 재료**지 학습자에게
그대로 보이는 문장이 아니고, 틀리면 그 단원 설명이 빗나가는 선에서 끝난다.
정답으로 채점하는 자리(24 확인 문항)와 달리 사람을 오판하지 않는다.
"""
from __future__ import annotations

SYSTEM = (
    "너는 교육과정 설계자다. 설명을 쓰지 않고 **무엇을 가르쳐야 하는지**만 적는다. "
    "출력은 지정한 JSON만 따른다."
)


def build_prompt(*, field: str, subject: str, items: list[str]) -> str:
    """`(분야, 과목, 항목들)` → 항목마다 `{name, teach, keywords}`.

    분야를 같이 주는 이유 — `정규화`는 데이터베이스에서 중복 제거고 머신러닝에서
    값 범위 맞추기다. 항목 이름만으로는 어느 쪽인지 모른다.
    """
    listing = "".join(f"{i}. {item}\n" for i, item in enumerate(items))
    return f"""「{field}」를 배우기 전에 필요한 **{subject}** 과목의 항목들이다.

[항목]
{listing}
각 항목에 대해 **가르칠 내용의 명세**를 써라. 설명 본문이 아니라 설계도다.

[규칙]
1. `teach`는 **한 문장**. "무엇을 이해하면 이 항목을 안다고 할 수 있는가"를 쓴다.
   설명하지 말고 범위를 정하라 — "스택은 LIFO다"가 아니라
   "LIFO 구조와 push/pop, 함수 호출 스택에서의 쓰임".
2. `keywords`는 3~6개. 그 항목을 설명할 때 반드시 나와야 하는 용어.
   문장이 아니라 용어여야 한다.
3. **「{field}」 맥락으로 쓴다.** 같은 이름이 분야마다 다른 것을 가리킨다.
4. 확실하지 않으면 지어내지 말고 `teach`를 빈 문자열로 둬라. 빠뜨리진 마라.
5. 번호를 빠뜨리지 마라. 항목 수와 답의 수가 같아야 한다.

JSON 하나만 출력한다(설명·코드펜스 금지):
{{"specs": {{"0": {{"teach": "...", "keywords": ["...", "..."]}}, "1": {{...}}}}}}"""
