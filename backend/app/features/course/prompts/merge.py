"""16' 과목 이름 합치기 — 같은 과목이 여러 이름으로 온다.

12.5 분야 판정은 자료 하나당 2회 호출한 **합집합**이고, 코스에는 자료가 여럿이다.
그래서 같은 과목이 매번 다른 이름으로 나온다. 실측(필기+실기 코스, 과목 15개):

    컴퓨터구조 · 컴퓨터 구조            공백만 다름
    정보보안 기초 · 정보 보안 기초       공백만 다름
    자료구조 · 자료구조와 알고리즘        뜻이 겹침
    컴퓨터 기초 · 컴퓨터 과학 기초        뜻이 겹침

**임베딩으로는 못 가른다.** 실측에서 같은 과목(AWS 기본 개념↔AWS 기본 서비스)이
0.806이고 다른 과목(네트워크 보안 기초↔네트워크 기초)이 0.866으로, 두 분포가
뒤집혀 있다. 이름 길이가 짧고 겹치는 단어가 많아서다.

그래서 LLM에게 시킨다. **판정이 아니라 병합**이라 안전하다 — 틀려도 과목이 하나
더 남거나 덜 남을 뿐이고, 항목은 그대로 다 남는다(합칠 때 항목을 버리지 않는다).
호출이 실패하면 아무것도 안 합친다.
"""
from __future__ import annotations

SYSTEM = (
    "너는 학습 과목 이름을 정리한다. 같은 과목을 가리키는 이름들을 하나로 묶고 "
    "대표 이름을 고른다. 출력은 지정한 JSON만 따른다."
)


def build_prompt(*, field: str, subjects: list[str]) -> str:
    """과목 이름 목록 → 묶음. 항목은 안 보여준다.

    항목까지 주면 "이 항목들이 겹치니 같은 과목"으로 기울어, 범위가 다른 두
    과목(네트워크 기초 / 네트워크 보안 기초)이 합쳐진다. 이름만 보고 판단하게 한다.
    """
    listing = "".join(f"{i}. {name}\n" for i, name in enumerate(subjects))
    return f"""'{field or "미상"}' 분야를 배우기 전에 필요한 과목 목록이다.
자동 추출이라 **같은 과목이 여러 이름으로 들어 있다.**

[과목]
{listing}
같은 과목을 가리키는 번호끼리 묶어라.

[규칙]
1. **표기만 다른 것**은 반드시 묶는다. 예) `컴퓨터구조` = `컴퓨터 구조`
2. **한쪽이 다른 쪽을 품는 것**도 묶는다. 예) `자료구조` ⊂ `자료구조와 알고리즘`
3. **범위가 다르면 묶지 마라.** 예) `네트워크 기초` ≠ `네트워크 보안 기초`,
   `데이터베이스 기초` ≠ `데이터베이스 튜닝`
4. 대표 이름은 그 묶음의 번호 중에서 고른다. 새 이름을 지어내지 마라.
   가장 널리 쓰이고 범위를 정확히 나타내는 것을 고른다.
5. 혼자인 과목은 묶음에 넣지 마라. 애매하면 묶지 마라(따로 두는 쪽이 안전하다).

JSON 하나만 출력한다(설명·코드펜스 금지):
{{"groups": [{{"canonical": 번호, "members": [번호, 번호]}}]}}"""
