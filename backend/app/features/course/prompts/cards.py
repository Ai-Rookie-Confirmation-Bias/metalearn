"""24 ③ 카드 4장 — 같은 개념을 네 가지 방식으로 쓴다.

**진술문을 안 쓰는 이유.** "나는 비유로 설명하면 잘 이해한다" 같은 자기평가는
실측 4/6이었고, 무엇보다 사람들이 자기 스타일을 잘 모른다. 실물을 보여주고
"어느 게 편한가"를 고르게 하는 편이 정확하다.

⚠️ 스타일 맞춤에 **학습 효과 근거는 없다**(meshing hypothesis, Pashler 2008).
이건 성취가 아니라 **이탈**을 막는 장치다 — 읽기 싫은 형식이면 안 읽는다.
화면 문구도 "당신에게 맞는 학습법"이 아니라 "어떤 설명이 읽기 편한가"여야 한다.

설명 생성은 실측 4/4로 안전했다. 조건이 "거짓말하지 마라" 하나뿐이라 그렇다.
"""
from __future__ import annotations

SYSTEM = (
    "너는 같은 내용을 여러 형식으로 쓰는 도구다. "
    "네 글은 형식만 다르고 담은 사실은 같아야 한다. "
    "출력은 지정한 JSON만 따른다."
)

STYLES = ("metaphor", "definition", "table", "why")


def build_prompt(*, concept: str, definition: str, source: str = "") -> str:
    """개념 하나를 네 형식으로. 학습자는 이 넷 중 하나를 고른다."""
    ground = f"\n[교재 원문]\n{source.strip()[:1500]}\n" if source.strip() else ""
    return f"""아래 개념 하나를 **네 가지 방식**으로 설명하라.
같은 사실을 담되 형식만 다르게 한다.

[개념] {concept}
[정의] {definition or "(정의 없음 — 원문을 근거로 쓴다)"}{ground}

[네 가지]
1. metaphor   — 일상 경험에 빗댄다. 두세 문장.
2. definition — 사전식 정의. 군더더기 없이 한두 문장.
3. table      — 마크다운 표. 항목 3~4줄. 비교하거나 나열할 축을 잡아라.
4. why        — **왜 이게 필요한가.** 없으면 무슨 문제가 생기는지로 시작한다.
                두세 문장.

[규칙]
· 넷 다 **같은 사실**을 담아야 한다. 한쪽에만 있는 내용을 넣지 마라.
· 위 정의(와 원문)에 없는 사실을 지어내지 마라. 비유의 소재는 밖에서 가져와도 된다.
· 길이를 비슷하게 맞춰라 — 길이로 고르게 되면 형식을 고른 게 아니다.
· "정의에 따르면" 같은 메타 표현을 쓰지 마라. 학습자가 읽을 글이다.

JSON 하나만 출력한다(설명·코드펜스 금지):
{{"metaphor": "...", "definition": "...", "table": "...", "why": "..."}}"""
