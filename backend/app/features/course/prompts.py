"""코스 층 프롬프트 — 선수 항목 회색지대 판정.

여기서 LLM에게 시키는 건 **필터**지 판정이 아니다. 물음이 하나뿐이고, 틀려도
항목 하나가 목록에 더 남거나 덜 남을 뿐이다. 사람을 오판하지 않는다.

**묻는 방식이 결과를 갈랐다.** 처음엔 "이 자료가 이걸 가르치나, 전제하나"로
물으면서 자료 안의 비슷한 개념을 근거로 보여줬다. 그랬더니 `라우팅 기초`가
`라우팅`(AWS 라우팅 테이블)과 닮았다는 이유로 "가르친다"가 나왔다. 이름이
닮았다는 건 임베딩이 이미 판단했는데 그걸 또 보여주니 같은 판단을 반복한 것이다.

그래서 **학습자 관점**으로 바꿨다. "이걸 모르는 사람이 이 자료를 읽을 수
있는가." 이게 우리가 실제로 알아야 하는 것이기도 하다.
"""
from __future__ import annotations

SYSTEM = (
    "너는 학습 설계자다. 어떤 주제를 모르는 사람이 주어진 자료를 읽을 수 "
    "있는지 판단한다. 출력은 지정한 JSON만 따른다."
)


def build_prompt(
    *, field: str, topics: list[str], items: list[str]
) -> str:
    """회색지대 항목들을 한 번에 묻는다.

    자료 안의 유사 개념은 **일부러 주지 않는다.** 그건 임베딩이 이미 본 정보고,
    다시 보여주면 "닮았으니 가르친다"로 기울어 범위 차이를 못 본다.
    목차만 주고 범위를 스스로 가늠하게 한다.
    """
    lines = [
        f"아래는 '{field or '미상'}' 분야 학습 자료의 목차다.\n\n",
        "".join(f"- {t}\n" for t in topics),
        "\n이 자료를 처음 펴는 사람을 생각하라. 아래 각 주제에 대해:\n\n",
        "  · 그걸 **모르면 이 자료를 못 읽는다** → 선수 지식이다 (prereq)\n"
        "  · 그걸 **이 자료가 처음부터 설명해 준다** → 자료의 내용이다 (covered)\n\n",
        "주의: 이 자료가 그 주제를 **쓰기만** 하는 것과 **가르치는** 것은 다르다.\n"
        "  예) 자료가 'AWS 라우팅 테이블 설정'을 다뤄도, 라우팅이 무엇이고 왜\n"
        "      필요한지를 설명하지 않는다면 '라우팅 원리'는 prereq다.\n"
        "  예) 목차에 '서브넷 만들기'가 있으면 '서브넷 만들기'는 covered다.\n\n",
        "[판단할 주제]\n",
    ]
    for i, item in enumerate(items):
        lines.append(f"{i}. {item}\n")

    lines.append(
        '\nJSON: {"covered": [번호...]}  ← 이 자료가 처음부터 설명해 주는 것만.\n'
        "선수 지식은 넣지 마라. 애매하면 넣지 마라(선수 쪽으로 둔다)."
    )
    return "".join(lines)
