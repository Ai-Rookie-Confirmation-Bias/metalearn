"""8단계 개념 추출 프롬프트.

**개념은 학습 단위가 아니라 진단 태그다.** 학습 단위는 목차(7단계)가 맡는다.
그래서 개념은 "이 사람이 뭘 아는지 모르는지 물어볼 만한 것"이면 충분하고,
원문의 모든 용어를 담을 필요가 없다.

기존 프롬프트는 "하나도 빠짐없이 전부, 요약·압축하지 말 것"이라고 지시했다.
개념이 곧 학습 단위였던 옛 설계의 문장인데, 그대로 두니 3,600자 조각에서
개념이 63개 나왔다. 그 안에 이런 것들이 섞였다:

    ÷(나눗셈) · ∩(교집합) · σ(시그마) · AND(∧) · ㅡ(차집합)
    제1정규형 · 제2정규형 · 제3정규형 · 제4정규형 · 제5정규형

연산자 기호 하나하나가 개념이 되고, 한 주제의 하위 단계가 전부 쪼개졌다.
전체 비용의 80%를 써서 만든 결과가 용어 사전에 가까웠다.

유지한 것:
  - 수식 평문화 복원   → Document Parse가 위첨자를 평문화한다
  - 슬러그 동시 산출   → 추가 비용 0
  - prerequisites 객체 배열 강제 → 문자열로 뱉는 형식 이탈이 잦다
"""
from __future__ import annotations

from app.core.config import settings

# 조각당 개념 상한은 settings.CONCEPT_MAX_PER_SEGMENT.

SYSTEM = (
    "너는 학습 자료를 '개념(Concept)' 단위로 파편화하는 지식 그래프 추출기다. "
    "출력은 반드시 지정한 JSON 스키마만 따른다. 설명·사족·마크다운 펜스 금지."
)


def build_prompt(
    topic_title: str,
    heading: str | None,
    segment_text: str,
    *,
    numbered: bool = False,
) -> str:
    """조각 하나 → 개념 추출 요청.

    목차 제목을 함께 준다. 같은 용어라도 어느 단원에서 나왔는지에 따라
    다루는 층위가 달라지기 때문이다.

    numbered면 원문이 "[n] 문장" 형태로 들어오고, 개념마다 근거 문장
    번호를 받는다. 원문을 바꿔 보여주는 게 아니라 5-b가 이미 나눈 문장에
    번호만 붙인 것이라, 표·수식은 한 덩어리 그대로 유지된다.
    """
    location = f"{topic_title} > {heading}" if heading else topic_title
    return (
        "다음은 학습 자료의 한 조각이다.\n"
        f"조각 위치: {location}\n\n"
        "이 조각에서 **학습자에게 따로 물어볼 만한 개념**을 추출하라.\n"
        "시험 문제의 주제가 되거나, '이거 아세요?'라고 물었을 때 설명을 요구할 "
        "수 있는 단위여야 한다.\n\n"
        "규칙:\n"
        f"1. **최대 {settings.CONCEPT_MAX_PER_SEGMENT}개.** 이 조각의 핵심부터 채우고, "
        f"{settings.CONCEPT_MAX_PER_SEGMENT}개를 넘기지 말 것. 원문의 모든 용어를 담는 게 아니라 "
        "물어볼 만한 것만 고르는 작업이다.\n"
        "2. **개념이 아닌 것** — 아래는 절대 개념으로 만들지 말 것:\n"
        "   - 기호·연산자 표기 자체 (÷, ∩, σ, AND(∧), ▷◁)\n"
        "   - 목록의 개별 항목이나 명령어 하나하나 (COMMIT, ls, -rw-r--r--)\n"
        "   - 예시로 든 값·숫자·약어 나열\n"
        "   - '목적', '특징', '장점', '종류' 같은 문서 구조 단어\n"
        "3. **묶을 수 있으면 묶어라.** 한 주제의 하위 단계·변형은 상위 개념 "
        "하나로 낸다 (제1~5정규형 → '정규화', 세 가지 조인 → '조인 연산'). "
        "세부는 description에 적는다.\n"
        "4. 반대로, 서로 헷갈리기 쉬워 따로 물어야 하는 대비 개념은 나눈다 "
        "(DAC / MAC, 페이징 / 세그먼테이션).\n"
        "5. prerequisites 에는 해당 개념을 이해하기 위해 '직접' 선행돼야 하는 "
        "개념만. 이 자료에 없는 외부 배경지식이라도 이해에 필요하면 포함하라.\n"
        f"6. 트리 중첩 깊이는 최대 {settings.MAX_CONCEPT_DEPTH}단계까지만. "
        f"초과 깊이는 자동 삭제되므로 {settings.MAX_CONCEPT_DEPTH}단계 이내로 유지할 것.\n"
        "7. name 은 간결한 명사구, description 은 한국어 한 문장. "
        "같은 개념은 한 번만 낸다.\n"
        "8. 원문은 PDF 파싱 과정에서 문장 속 수식의 위첨자·특수기호가 "
        "평문화되어 있을 수 있다(예: 'x2+x'는 x^2+x, 'ex'는 e^x). "
        "수학 맥락으로 원래 수식을 복원해 표준 표기(x^2, e^x 꼴)로 적을 것.\n"
        "9. 모든 개념(선수 포함)에 key 필드로 영문 슬러그를 함께 산출하라 — "
        '소문자 영단어를 하이픈으로 연결한 의미 번역(음차 금지, 예: "이진 탐색 트리"→'
        '"binary-search-tree").\n'
        + (
            "10. **각 개념마다 evidence 필드에 근거 문장 번호 배열을 반드시 "
            "반환하라.** 원문 앞에 붙은 [숫자]가 문장 번호다. 그 개념이 실제로 "
            "설명·언급된 문장만 고른다(보통 1~3개). 번호만 담은 정수 배열이며, "
            "원문에서 근거를 특정할 수 없으면 빈 배열 []로 둔다 — 없는 번호를 "
            "지어내지 말 것. 교재 밖 배경지식인 선수개념은 빈 배열이 정상이다.\n"
            if numbered
            else ""
        )
        + "\n"
        + (
            'JSON 형식: {"concepts":[{"name":str,"description":str,"key":str,'
            '"evidence":[int],"prerequisites":[{ ...동일 구조... }]}]}\n'
            if numbered
            else 'JSON 형식: {"concepts":[{"name":str,"description":str,"key":str,'
            '"prerequisites":[{ ...동일 구조... }]}]}\n'
        )
        + "주의: prerequisites 는 문자열 배열이 아니라 반드시 동일 구조의 "
        "객체 배열이어야 한다.\n\n"
        + ("=== 조각 원문 (문장 번호 부여) ===\n" if numbered else "=== 조각 원문 ===\n")
        + f"{segment_text}"
    )


def number_sentences(sentences: list[str]) -> str:
    """문장 목록 → "[n] 문장" 본문.

    원문을 고치는 게 아니라 번호만 앞에 붙인다. 5-b가 표·수식을 한 덩어리로
    두므로 여기서도 쪼개지지 않는다.
    """
    return "\n".join(f"[{i}] {text}" for i, text in enumerate(sentences))
