"""12.5단계 분야 판정 프롬프트.

묻는 건 두 가지다 — "이 자료는 무슨 분야인가", "펴기 **전에** 알아야 하는 건
무엇인가". 후자가 목적이고 전자는 그걸 위한 발판이다.

**이게 책 밖 선수를 찾는 유일한 경로다.** 반대 방향(원문의 끊긴 고리에서
찾기)은 폐기했다 — 책이 언급조차 안 한 선수는 원문에서 나올 수가 없고, 실측에
서 끊긴 고리 55개가 대부분 그 책이 가르치는 내용이었다.

실측에서 걸린 두 가지를 프롬프트로 막는다:

  ① **그 책이 가르치는 걸 선수라고 뱉는다.** 정처기 필기 자료에 `데이터베이스
     기초`가 나왔는데 목차 3번이 "데이터베이스 구축"이다. 프롬프트로 완전히는
     못 막는다 — 그래서 16'단계가 임베딩으로 다시 거른다. 여기서는 줄이기만 한다.

  ② **이름이 매번 달라진다.** 같은 자료에 `데이터구조 기초` ↔ `알고리즘과
     자료구조`가 나온다. 그래서 2회 호출해 뜻으로 교집합을 잡는다(pipeline).
"""
from __future__ import annotations

SYSTEM = (
    "너는 교육과정 설계자다. 학습 자료를 보고 그 자료를 공부하기 **전에** "
    "갖춰야 할 배경 지식을 판단한다. 출력은 반드시 지정한 JSON 스키마만 따른다. "
    "모든 값은 한국어로 쓴다 — 널리 쓰이는 약어(OSI, TCP/IP, SQL 등)만 원문 표기."
)

# 프롬프트에 넣을 재료 개수. 1~2천 자에 맞춘 크기다.
TOP_CONCEPTS = 30
TOP_DANGLING = 20


def build_prompt(
    *,
    filename: str,
    topics: list[str],
    concepts: list[str],
    dangling: list[str],
) -> str:
    """분야 + 선수 과목을 한 번에 받는다.

    `subtopics`를 같이 받는 게 중요하다. "자료구조를 모른다"는 책 한 권을
    달라는 말이지만 "트리·그래프를 모른다"는 단원 둘이다. 나중에 조달할 때
    부담이 완전히 달라진다.

    `ordered`는 그 과목 안에서 순서가 강제되는지다 — 보강 **단원**이 되느냐
    한 **꼭지**가 되느냐를 가른다.
    """
    parts = [
        "아래는 어떤 학습 자료에서 자동 추출한 목차와 개념이다.\n\n",
        f"[파일명] {filename}\n",
    ]
    if topics:
        parts.append("[목차]\n" + "".join(f"- {t}\n" for t in topics))
    if concepts:
        parts.append("[주요 개념]\n" + ", ".join(concepts[:TOP_CONCEPTS]) + "\n")
    if dangling:
        parts.append(
            "[이 자료가 설명 없이 전제하는 용어]\n"
            + ", ".join(dangling[:TOP_DANGLING]) + "\n"
        )

    parts.append(
        "\n두 가지에 답하라.\n\n"
        "1) 이 자료는 무슨 분야이고 어느 수준인가?\n\n"
        "2) 이 자료를 공부하려면 **펴기 전에** 이미 알아야 하는 과목·분야는?\n\n"
        "   ★ 가장 중요한 규칙: **이 자료가 직접 가르치는 내용은 절대 넣지 마라.**\n"
        "     목차에 있는 주제는 선수가 아니다. 자료를 펴기 전에 이미 알고 있어야\n"
        "     하는 것만 답하라. 예를 들어 목차에 '데이터베이스 구축'이 있으면\n"
        "     '데이터베이스 기초'는 선수가 아니다 — 이 자료가 가르친다.\n\n"
        "   · 없으면 빈 배열로 답하라. 밑바닥부터 다 가르치는 자료는 선수가 없다.\n"
        "   · 과목마다 그 안에서 배우는 하위 항목을 배우는 순서대로 나열하라.\n"
        "   · ordered: 하위 항목 사이 순서가 반드시 지켜져야 하면 true,\n"
        "     아무 순서로 배워도 되면 false.\n"
        "   · why: 이 자료의 무엇 때문에 그게 필요한지 한 줄.\n\n"
        "JSON 스키마:\n"
        '{"field": str, "level": str, "prereq_subjects": ['
        '{"name": str, "why": str, "subtopics": [str], "ordered": bool}]}'
    )
    return "".join(parts)
