"""18단계 — 다른 자료의 같은 개념인지 확인하는 프롬프트.

**필터지 판정이 아니다.** 임베딩이 0.70~0.75로 좁혀 온 후보만 보고, 놓쳐도
연결 하나가 덜 생길 뿐이다.

이 구간이 필요한 이유는 실측에 있다. **이름만 닮은 딴것이 여기 섞인다:**

    정규화 ↔ 정규화              (같음)   0.72
    블루스나프 ↔ 블루버그          (다름)   0.72
    MD4 ↔ MD5                  (다름)   0.66

이름 임베딩으로는 못 가른다. 정의를 같이 보면 사람이든 LLM이든 가른다.
"""
from __future__ import annotations

SYSTEM = (
    "너는 학습 자료를 대조하는 검수자다. 서로 다른 자료에서 뽑힌 두 개념이 "
    "같은 것인지 판단한다. 출력은 지정한 JSON만 따른다."
)


def build_prompt(pairs: list[tuple[str, str, str, str]]) -> str:
    """pairs: (A 이름, A 정의, B 이름, B 정의)

    이름이 닮았다는 건 임베딩이 이미 확인했다. LLM이 볼 것은 **정의**다.
    """
    lines = [
        "서로 다른 학습 자료에서 뽑은 개념 쌍이다. 각 쌍이 **같은 개념**인지 "
        "판단하라.\n\n",
        "같은 개념이다:\n"
        "  · 표기만 다른 같은 것 (도커 / Docker, In-order / 중위 순회)\n"
        "  · 한쪽이 상위·하위지만 설명이 그대로 쓸 만한 것\n"
        "    (MVC 패턴 / 모델-뷰-컨트롤러 아키텍처)\n\n",
        "다른 개념이다:\n"
        "  · 이름만 닮은 딴것 (MD4 / MD5, 블루버그 / 블루스나프)\n"
        "  · 같은 분야의 이웃일 뿐인 것 (스택 / 큐, 정렬 / 탐색)\n\n",
        "[쌍 목록]\n",
    ]
    for i, (a_name, a_def, b_name, b_def) in enumerate(pairs):
        lines.append(f"{i}.\n")
        lines.append(f"   A: {a_name} — {(a_def or '(설명 없음)')[:120]}\n")
        lines.append(f"   B: {b_name} — {(b_def or '(설명 없음)')[:120]}\n")

    lines.append(
        '\nJSON: {"same": [번호...]}  ← 같은 개념인 쌍의 번호만.\n'
        "애매하면 넣지 마라."
    )
    return "".join(lines)
